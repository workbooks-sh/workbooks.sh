// gen-mcp-registry.mjs — build the studio's MCP catalog from the OFFICIAL MCP registry
// (registry.modelcontextprotocol.io). We keep ONLY LOCAL PACKAGE servers our WASM sandbox can RUN in-nexus:
// npm packages (JS/TS/Node → porffor → WASM, stdio emulated by washy). These run inside the sandbox like any
// other guest code — no external server. REMOTE (hosted SaaS) servers are intentionally EXCLUDED from the
// catalog — a remote one can still be added by hand (the "Add server" form). Python/oci/nuget are dropped
// (not WASM-runnable on our path). Emits src/lib/mcp.generated.js (lazy-loaded by the MCP browser).
//
// Run: node tools/gen-mcp-registry.mjs
import { writeFileSync } from 'node:fs'

const BASE = 'https://registry.modelcontextprotocol.io/v0/servers?limit=100'
const RUNNABLE_PKG = new Set(['npm']) // package registries we run in-sandbox (JS→WASM). +rust/go/c when packaged.

async function fetchAll() {
  const out = []
  let cursor = null
  for (let page = 0; page < 60; page++) {
    const url = BASE + (cursor ? '&cursor=' + encodeURIComponent(cursor) : '')
    const res = await fetch(url)
    if (!res.ok) throw new Error('registry ' + res.status)
    const d = await res.json()
    out.push(...(d.servers || []))
    cursor = d.metadata?.nextCursor
    if (!cursor) break
  }
  return out
}

const isLatest = (x) => x?._meta?.['io.modelcontextprotocol.registry/official']?.isLatest
const langOf = (pkgs, remotes) => {
  if (remotes?.length) return 'remote'
  const t = pkgs?.[0]?.registryType || pkgs?.[0]?.registry_type
  return t === 'npm' ? 'node' : t || 'unknown'
}

// LOCAL only: a server is in the catalog iff it ships a package we can run in-sandbox (npm). Remote-only
// servers are excluded (they're someone else's hosted service — add by hand if you really want one).
function compatible(srv) {
  return (srv.packages || []).some((p) => RUNNABLE_PKG.has(p.registryType || p.registry_type))
}

function toEntry(srv) {
  const pkg = (srv.packages || []).find((p) => RUNNABLE_PKG.has(p.registryType || p.registry_type))
  return {
    id: srv.name,
    name: srv.title || srv.name.split('/').pop(),
    description: (srv.description || '').slice(0, 200),
    version: srv.version || '',
    transport: 'stdio', // local package, run in the WASM sandbox with emulated stdio
    pkg: { registry: pkg.registryType || pkg.registry_type, identifier: pkg.identifier, version: pkg.version },
    lang: langOf(srv.packages, null),
    repo: srv.repository?.url || null
  }
}

const all = await fetchAll()
const latest = all.filter(isLatest)
const seen = new Set()
const entries = latest
  .map((x) => x.server)
  .filter((s) => s && compatible(s))
  .map(toEntry)
  .filter((e) => (seen.has(e.id) ? false : seen.add(e.id))) // dedupe by name
  .sort((a, b) => a.name.localeCompare(b.name))

const body = `// AUTO-GENERATED by tools/gen-mcp-registry.mjs from the official MCP registry. Do not edit by hand.
// WASM-compatible only: remote (HTTP) + npm (JS→WASM) servers; python/oci excluded. ${entries.length} servers.
export const mcpCatalog = ${JSON.stringify(entries, null, 0)}
`
writeFileSync(new URL('../src/lib/mcp.generated.js', import.meta.url), body)
const byLang = entries.reduce((m, e) => ((m[e.lang] = (m[e.lang] || 0) + 1), m), {})
console.log(`wrote ${entries.length} servers (of ${latest.length} latest, ${all.length} total) →`, byLang)
