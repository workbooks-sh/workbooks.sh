// Product-icon layer (Step 2b / B3): remap the workbench's chrome codicons to iconoir — the dash's own icon
// language — so the IDE stops reading as VS Code at the glyph level. A true product-icon-theme needs a custom
// font; for the demo we emit a CSS layer that masks each visible `.codicon-NAME` with the iconoir SVG (filled
// by currentColor, so it inherits our theme foreground). Curated to the glyphs actually on screen. Generated
// from the same iconoir set icons.js uses (no drift); regenerate: node tools/gen-ide-product-icons.mjs.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ICONOIR from '../node_modules/@iconify-json/iconoir/icons.json' with { type: 'json' }

const root = fileURLToPath(new URL('..', import.meta.url))

// codicon id -> iconoir name. Curated to the chrome we actually render (activity bar, explorer toolbar,
// tabs, panel, status bar, breadcrumbs, quick input). Missing iconoir names are skipped with a warning.
const MAP = {
  menu: 'menu', 'three-bars': 'menu',
  files: 'multiple-pages', 'file-directory': 'folder', folder: 'folder', 'folder-opened': 'folder',
  file: 'page', search: 'search', 'search-fuzzy': 'search',
  'chevron-right': 'nav-arrow-right', 'chevron-down': 'nav-arrow-down', 'chevron-up': 'nav-arrow-up',
  'chevron-left': 'nav-arrow-left', close: 'xmark', 'close-all': 'xmark', clear: 'xmark', 'panel-close': 'xmark',
  'new-file': 'page-plus-in', 'new-folder': 'folder-plus', refresh: 'refresh-double',
  'collapse-all': 'collapse', 'expand-all': 'expand', ellipsis: 'more-horiz', more: 'more-horiz',
  gear: 'settings', settingsGear: 'settings', account: 'user', bell: 'bell', 'bell-dot': 'bell',
  terminal: 'terminal', output: 'terminal-tag', error: 'warning-circle', warning: 'warning-triangle',
  info: 'info-circle', add: 'plus', remove: 'minus', edit: 'edit-pencil', trash: 'trash',
  'split-horizontal': 'view-columns-3', 'layout-panel': 'view-grid', 'list-flat': 'list',
  'arrow-left': 'arrow-left', 'arrow-right': 'arrow-right', check: 'check', 'circle-filled': 'circle',
  'kebab-vertical': 'more-vert', 'go-to-file': 'page-search', 'symbol-file': 'page'
}

const enc = (svg) => encodeURIComponent(svg).replace(/'/g, '%27').replace(/"/g, '%22')
const rules = []
const skipped = []
for (const [codicon, iconoir] of Object.entries(MAP)) {
  const ic = ICONOIR.icons[iconoir]
  if (!ic) { skipped.push(`${codicon}->${iconoir}`); continue }
  const w = ic.width || ICONOIR.width || 24, h = ic.height || ICONOIR.height || 24
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${w} ${h}'>${ic.body.replaceAll('currentColor', '%23000')}</svg>`
  const uri = `url("data:image/svg+xml,${enc(svg)}")`
  rules.push(
`.codicon.codicon-${codicon}::before{content:'';display:inline-block;width:16px;height:16px;background-color:currentColor;-webkit-mask:${uri} center/contain no-repeat;mask:${uri} center/contain no-repeat;}`)
}

const banner = '/* GENERATED by tools/gen-ide-product-icons.mjs — do not edit. iconoir->codicon chrome remap. */\n'
writeFileSync(root + 'src/lib/ide/product-icons.generated.css', banner + rules.join('\n') + '\n')
console.log('wrote product-icons.generated.css —', rules.length, 'codicon remaps', skipped.length ? '(skipped: ' + skipped.join(', ') + ')' : '')
