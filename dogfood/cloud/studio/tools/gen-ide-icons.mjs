// Generate the Workbooks FILE ICON THEME for the workbench explorer (Step 2 / B3). Reuses the SAME icon
// language as our own Files surface: colorful vscode-icons for file types + a branded green iconoir sparks for
// .work, and neutral iconoir folder/file defaults. Emits a committed artifact the workbench registers via the
// file-icon-theme contribution. Single source of truth = the same iconify sets icons.js uses (no drift).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ICONOIR from '../node_modules/@iconify-json/iconoir/icons.json' with { type: 'json' }
import VSCODE from '../node_modules/@iconify-json/vscode-icons/icons.json' with { type: 'json' }

const root = fileURLToPath(new URL('..', import.meta.url))

const svg = (set, name, recolor) => {
  const ic = set.icons[name]
  if (!ic) return null
  const w = ic.width || set.width || 24, h = ic.height || set.height || 24
  const body = recolor ? ic.body.replaceAll('currentColor', recolor) : ic.body
  return `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 ${w} ${h}">${body}</svg>`
}

// extension -> vscode-icons glyph (mirrors FILE_ICON in src/lib/icons.js)
const FILE_TYPE = {
  svelte: 'file-type-svelte', rs: 'file-type-rust', ex: 'file-type-elixir', exs: 'file-type-elixir',
  js: 'file-type-js', mjs: 'file-type-js', cjs: 'file-type-js', jsx: 'file-type-reactjs',
  ts: 'file-type-typescript', tsx: 'file-type-reactjs', json: 'file-type-json', md: 'file-type-markdown',
  css: 'file-type-css', html: 'file-type-html', toml: 'file-type-toml', yaml: 'file-type-yaml', yml: 'file-type-yaml',
  go: 'file-type-go', zig: 'file-type-zig', lua: 'file-type-lua', txt: 'file-type-text', lock: 'file-type-yaml',
  svg: 'file-type-svg', csv: 'file-type-text', png: 'file-type-image', jpg: 'file-type-image', gif: 'file-type-image'
}

const BLOOM = '#3fe081', DIM = '#8c9189'
const files = {}   // pathInExtension -> svg string
const iconDefinitions = {}
const fileExtensions = {}

// .work — branded green sparks (iconoir)
files['./icons/work.svg'] = svg(ICONOIR, 'sparks', BLOOM)
iconDefinitions._work = { iconPath: './icons/work.svg' }
fileExtensions.work = '_work'

// file types — colorful vscode-icons
for (const [ext, glyph] of Object.entries(FILE_TYPE)) {
  const s = svg(VSCODE, glyph)
  if (!s) continue
  const key = '_ft_' + ext
  files[`./icons/${key}.svg`] = s
  iconDefinitions[key] = { iconPath: `./icons/${key}.svg` }
  fileExtensions[ext] = key
}

// neutral defaults — iconoir, dim
files['./icons/file.svg'] = svg(ICONOIR, 'empty-page', DIM)
files['./icons/folder.svg'] = svg(ICONOIR, 'folder', DIM)
files['./icons/folder-open.svg'] = svg(ICONOIR, 'folder', BLOOM)
iconDefinitions._file = { iconPath: './icons/file.svg' }
iconDefinitions._folder = { iconPath: './icons/folder.svg' }
iconDefinitions._folderOpen = { iconPath: './icons/folder-open.svg' }

const theme = {
  iconDefinitions,
  file: '_file',
  folder: '_folder',
  folderExpanded: '_folderOpen',
  fileExtensions,
  fileNames: { 'index.work': '_work', 'readme.md': '_ft_md' },
  hidesExplorerArrows: false
}

const banner = '// GENERATED by tools/gen-ide-icons.mjs — do not edit. Regenerate: node tools/gen-ide-icons.mjs\n'
const missing = Object.entries(files).filter(([, v]) => !v).map(([k]) => k)
if (missing.length) throw new Error('missing svgs: ' + missing.join(', '))
writeFileSync(root + 'src/lib/ide/icons.generated.js',
  banner + 'export const iconTheme = ' + JSON.stringify(theme) + '\nexport const iconFiles = ' + JSON.stringify(files) + '\n')
console.log('wrote src/lib/ide/icons.generated.js —', Object.keys(files).length, 'icons,', Object.keys(fileExtensions).length, 'extension maps')
