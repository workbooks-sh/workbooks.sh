//! The Work kernel — the engine's real front-end + renderer.
//!
//! ONE format: `work-*` web components. The kernel parses the Work front-end
//! (the `.work` shorthand and the HTML element tree share one [`work::Node`]
//! model) and reads its structure:
//!   - parse_headlines : the query surface (structure → rows)
//!   - tangle_plan     : a WIT-world-shaped build plan (work-flow → world)
//!   - validate        : diagnostics over the plan (dangling inputs, no lang)
//!   - check_upgrade   : diff a deployed world vs a new one, gate breaking changes
//!   - render          : Work → `work-*` HTML (work::render_work)
//!
//! Everything is `element + values + nesting + prose`. Org's special fields
//! (TODO state, tags, drawers, source-block header args, SCHEDULED/DEADLINE)
//! are plain attributes on `work-*` elements now — one mechanism, no syntax per
//! concept. See docs/WORK-FORMAT.md. Pure in / pure out, no host calls — the
//! same wasm runs in every surface.
//!
//! The boundary is a WIT-typed Component (the `workbooks:oql` world): every
//! export is string→string, generated by cargo-component. No `unsafe`, no
//! hand-rolled ptr/len ABI — the kernel rides the same Component Model it
//! imposes on user code. The export names + JSON shapes are unchanged: only the
//! front-end syntax behind them moved from org to Work.

use std::collections::{BTreeMap, BTreeSet};

// The Work format: generic Node tree + `.work` shorthand parser + work-* HTML
// renderer (the canonical front-end). See docs/WORK-FORMAT.md.
pub mod work;

// Pure, host-injected time math (no clock, no I/O). The kernel computes *when*
// schedules fire; the host's scheduler fires them. See docs/WORK-FORMAT.md.
pub mod work_time;

use work::Node;

// ── Public kernel API ─────────────────────────────────────────────────────
// Pure string→string functions. The native build (e.g. the `wb` CLI) links
// these as a normal rlib; the wasm Component below wraps the SAME functions.
// One logic, both surfaces — there is no "wasm version" of the kernel logic.

pub fn parse_headlines(src: &str) -> String {
    let arr: Vec<_> = flatten(&work::parse_work(src))
        .iter()
        .map(|(level, n)| {
            serde_json::json!({
                "level": level,
                "title": title_of(n),
                "state": state_of(n),
                "id": n.attrs.get("id"),
                "tags": tags_of(n),
                "props": props_of(n),
                "scheduled": schedule_json(n),
                "deadline": deadline_json(n),
            })
        })
        .collect();
    serde_json::to_string(&arr).unwrap_or_else(|_| "[]".into())
}

pub fn lint(_src: &str) -> String {
    "[]".into()
}

pub fn tangle_plan(src: &str) -> String {
    build_plan(src).to_string()
}

pub fn validate(src: &str) -> String {
    let roots = work::parse_work(src);
    let mut diags = vec![];
    walk_flows(&roots, &mut |flow| {
        let comps = comps_of(flow);
        let produced: BTreeSet<&str> = comps.iter().filter_map(|c| c.out.as_deref()).collect();
        for c in &comps {
            if c.lang.is_none() {
                diags.push(diag("error", &c.name, "component has no source block / language"));
            }
            if let Some(inp) = &c.inp {
                if !produced.contains(inp.as_str()) {
                    diags.push(diag(
                        "error",
                        &c.name,
                        &format!("input `{}` has no upstream producer", inp),
                    ));
                }
            }
        }
    });
    serde_json::to_string(&diags).unwrap_or_else(|_| "[]".into())
}

// Diff a deployed Workbook against a new one and gate breaking changes,
// WIT/Candid-subtyping style: exports may grow, never shrink; imports may
// shrink, never grow; a component's output type may not change. Empty
// diagnostics means the upgrade is safe.
pub fn check_upgrade(old: &str, new: &str) -> String {
    let old = world_sigs(old);
    let new = world_sigs(new);

    let mut diags = vec![];
    for (name, os) in &old {
        let Some(ns) = new.get(name) else {
            diags.push(diag("error", name, "workflow removed (breaking)"));
            continue;
        };
        for e in &os.exports {
            if !ns.exports.contains(e) {
                diags.push(diag("error", name, &format!("export `{}` removed (breaking)", e)));
            }
        }
        for i in &ns.imports {
            if !os.imports.contains(i) {
                diags.push(diag("warn", name, &format!("new capability `{}` now required", i)));
            }
        }
        for (c, oout) in &os.comp_out {
            if let Some(nout) = ns.comp_out.get(c) {
                if oout != nout {
                    diags.push(diag(
                        "error",
                        name,
                        &format!("component `{}` output type changed (breaking)", c),
                    ));
                }
            }
        }
    }
    serde_json::to_string(&diags).unwrap_or_else(|_| "[]".into())
}

pub fn render(src: &str) -> String {
    work::render_work(src)
}

// Pure next-fire helper: given a cron expression and an injected `now` (an
// ISO-8601 instant string), return the first fire time strictly AFTER `now` as
// an ISO-8601 string, or `null` when the cron is invalid / never fires within
// the horizon. The kernel NEVER reads the clock — `now` is always supplied by
// the host, which then performs the actual firing. This is the kernel's whole
// role in scheduling: compute when, never trigger.
pub fn next_fire(cron: &str, now: &str) -> String {
    let result = work_time::Cron::parse(cron)
        .zip(work_time::Instant::parse(now))
        .and_then(|(c, n)| c.next_after(&n))
        .map(|i| i.format());
    match result {
        Some(at) => serde_json::json!({ "at": at }).to_string(),
        None => serde_json::json!({ "at": serde_json::Value::Null }).to_string(),
    }
}

