// Extension manifest generator — the COMPLETE Open VSX registry, baked into a committed artifact (mirrors
// gen-registry.mjs for toolkits). The search API is offset-capped at 10k, so we take the SITEMAP
// (open-vsx.org/sitemap.xml) which lists every extension (/extension/<ns>/<name> + lastmod) in one file — the
// full ~15k. We merge in source-repo URLs from EclipseFdn/publish-extensions (provenance for license review).
// Rich metadata (icon/desc/downloads) + license stay on-demand via the live API; this is the authoritative
// INDEX (count, enumeration, vendoring source). Run: node tools/gen-extensions.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SITEMAP = 'https://open-vsx.org/sitemap.xml'
const PUBLISH = 'https://raw.githubusercontent.com/EclipseFdn/publish-extensions/master/extensions.json'

console.log('fetching sitemap …')
const xml = await (await fetch(SITEMAP)).text()

// parse <loc>…/extension/<ns>/<name></loc> + adjacent <lastmod>
const entries = []
const re = /<loc>https:\/\/open-vsx\.org\/extension\/([^/]+)\/([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g
let m
while ((m = re.exec(xml))) entries.push({ ns: m[1], name: m[2], id: `${m[1]}.${m[2]}`, updated: m[3] })
console.log(`sitemap: ${entries.length} extensions`)

// merge source-repo provenance from publish-extensions (curated subset, keyed by ns.name)
let repos = {}
try {
  const pub = JSON.parse(await (await fetch(PUBLISH)).text())
  const obj = pub && typeof pub === 'object' && !Array.isArray(pub) ? pub : {}
  for (const [id, v] of Object.entries(obj)) {
    if (id.startsWith('$')) continue
    if (v && v.repository) repos[id] = String(v.repository).replace(/\.git$/, '')
  }
  console.log(`publish-extensions: ${Object.keys(repos).length} with source repos`)
} catch (e) { console.warn('publish-extensions merge skipped:', e.message) }

let withRepo = 0
for (const e of entries) { if (repos[e.id]) { e.repo = repos[e.id]; withRepo++ } }

// the heavy manifest (lazy-imported only when browsing the full set)
const js = `// GENERATED by tools/gen-extensions.mjs — do not edit by hand. The COMPLETE Open VSX registry index
// (${entries.length} extensions, from the sitemap). ${withRepo} carry a source repo (EclipseFdn/publish-extensions)
// for license/provenance. Rich metadata + license are fetched on demand via dock.ext (the live API). ~1.5MB —
// lazy-import this only for full-set browse; use extensions.count.js for the cheap total.
export const extensionManifest = ${JSON.stringify(entries)}
`
writeFileSync(join(ROOT, 'src', 'lib', 'extensions.generated.js'), js)
// the cheap count constant (safe to import anywhere — e.g. the Toolkits nav badge)
writeFileSync(join(ROOT, 'src', 'lib', 'extensions.count.js'),
  `// GENERATED by tools/gen-extensions.mjs — the Open VSX registry total (cheap import; full index is\n// extensions.generated.js).\nexport const EXTENSION_COUNT = ${entries.length}\n`)
console.log(`→ src/lib/extensions.generated.js (${entries.length}, ${withRepo} with repo) + extensions.count.js`)
